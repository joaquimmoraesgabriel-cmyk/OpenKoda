"""Emit a deterministic SQL seed from immutable Git blobs; never execute skill resources."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

REVISION = "5863806dd4e15c63174bee4e7515a4256792ecfa"
SOURCE = "https://github.com/mattpocock/skills"


def catalogue(repo):
    def git(*args):
        return subprocess.check_output(["git", "-C", str(repo), *args]).decode("utf-8")

    if git("rev-parse", REVISION + "^{commit}").strip() != REVISION:
        raise ValueError("Unexpected source revision")
    license_text = git("show", REVISION + ":LICENSE")
    if not license_text.startswith("MIT License\n") or "Copyright (c) 2026 Matt Pocock" not in license_text:
        raise ValueError("Unexpected license")
    blobs = {}
    for entry in git("ls-tree", "-rz", REVISION, "--", "skills").split("\0"):
        if not entry:
            continue
        header, path = entry.split("\t", 1)
        mode, kind, sha = header.split()
        if kind != "blob" or mode not in ("100644", "100755") or not re.fullmatch(r"[A-Za-z0-9_./-]+", path):
            raise ValueError("Unsupported skill resource")
        blobs[path] = sha
    entries = []
    for filename, sha in sorted(blobs.items()):
        if not filename.endswith("/SKILL.md"):
            continue
        folder = filename.removesuffix("SKILL.md")
        body = git("cat-file", "blob", sha)
        front = body.split("---\n", 2)[1]
        def field(key):
            match = re.search(r"^" + key + r":[ \t]*(.+)$", front, re.M)
            if not match:
                raise ValueError(f"Missing {key} in {filename}")
            raw = match[1].strip()
            return json.loads(raw) if raw.startswith('"') else raw
        name = field("name")
        if not re.fullmatch(r"[a-z0-9-]+", name):
            raise ValueError("Invalid skill identifier")
        explicit = re.search(r"^disable-model-invocation:\s*true\s*$", front, re.M)
        resources = {path[len(folder):]: git("cat-file", "blob", digest)
                     for path, digest in sorted(blobs.items()) if path.startswith(folder) and path != filename}
        entries.append(dict(id=name, name=name, description=field("description"), revision=REVISION,
                            invocation="explicit" if explicit else "automatic_or_explicit", body=body,
                            resources=resources, license=license_text, source=f"{SOURCE}/tree/{REVISION}/{folder[:-1]}"))
    if len(entries) != 39 or len({s["id"] for s in entries}) != len(entries):
        raise ValueError("Unexpected catalogue manifest")
    return entries, license_text


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--license", type=Path)
    args = parser.parse_args()
    entries, license_text = catalogue(args.repo)
    payload = json.dumps(entries, ensure_ascii=False, separators=(",", ":"))
    delimiter = "$openkoda_skills_5863806$"
    if delimiter in payload:
        raise ValueError("SQL delimiter collision")
    sql = ("-- Generated by supabase/catalog/import.py from " + SOURCE + " @ " + REVISION + ".\n"
           "insert into openkoda_private.skills (id,name,description,revision,invocation,body,resources,license,source)\n"
           "select id,name,description,revision,invocation,body,resources,license,source\n"
           f"from jsonb_to_recordset({delimiter}{payload}{delimiter}::jsonb)\n"
           "as s(id text,name text,description text,revision text,invocation text,body text,resources jsonb,license text,source text)\n"
           "on conflict(id) do update set name=excluded.name,description=excluded.description,revision=excluded.revision,\n"
           "invocation=excluded.invocation,body=excluded.body,resources=excluded.resources,license=excluded.license,source=excluded.source;\n")
    if args.output:
        args.output.write_bytes(sql.encode("utf-8"))
    else:
        sys.stdout.buffer.write(sql.encode("utf-8"))
    if args.license:
        args.license.write_bytes(license_text.encode("utf-8"))
